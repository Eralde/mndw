import {Window} from 'happy-dom';

export interface IconSource {
  name: string;
  svg: string;
}

export interface IconAssets {
  sprite: string;
  names: string;
}

interface IconElement {
  tagName: string;
  attributes: readonly (readonly [string, string])[];
  children: readonly IconElement[];
}

interface ParsedIcon {
  name: string;
  attributes: readonly (readonly [string, string])[];
  children: readonly IconElement[];
}

const SVG_NAMESPACE = 'http://www.w3.org/2000/svg';
const REQUIRED_VIEW_BOX = '0 0 24 24';
const ICON_NAME_PATTERN = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const SYMBOL_ID_PREFIX = 'mndw-icon-';
const GENERATOR_HEADER = '<!-- GENERATED by frontend/ui/scripts/generate-icons.ts — do not edit by hand. -->';
const NAMES_HEADER = '/* GENERATED by frontend/ui/scripts/generate-icons.ts — do not edit by hand. */';

const ROOT_DISCARDED_ATTRIBUTES: ReadonlySet<string> = new Set(['xmlns', 'width', 'height', 'class']);

const PRESENTATION_ATTRIBUTES: ReadonlySet<string> = new Set([
  'clip-rule',
  'fill',
  'fill-opacity',
  'fill-rule',
  'opacity',
  'stroke',
  'stroke-dasharray',
  'stroke-dashoffset',
  'stroke-linecap',
  'stroke-linejoin',
  'stroke-miterlimit',
  'stroke-opacity',
  'stroke-width',
  'transform',
]);

const GEOMETRY_ATTRIBUTES: Readonly<Record<string, ReadonlySet<string>>> = {
  circle: new Set(['cx', 'cy', 'r']),
  ellipse: new Set(['cx', 'cy', 'rx', 'ry']),
  g: new Set<string>(),
  line: new Set(['x1', 'x2', 'y1', 'y2']),
  path: new Set(['d']),
  polygon: new Set(['points']),
  polyline: new Set(['points']),
  rect: new Set(['height', 'rx', 'ry', 'width', 'x', 'y']),
};

export function buildIconAssets(sources: readonly IconSource[], license: string): IconAssets {
  const seen = new Set<string>();
  const parsed: ParsedIcon[] = [];

  for (const source of sources) {
    if (!ICON_NAME_PATTERN.test(source.name)) {
      throw new Error(`Invalid icon name "${source.name}": expected lowercase kebab-case segments.`);
    }
    if (seen.has(source.name)) {
      throw new Error(`Duplicate icon name "${source.name}".`);
    }
    seen.add(source.name);
    parsed.push(parseIcon(source));
  }

  parsed.sort((left, right) => left.name.localeCompare(right.name));
  const names = parsed.map((icon) => icon.name);

  return {
    sprite: buildSprite(parsed, license),
    names: buildNames(names),
  };
}

function parseIcon(source: IconSource): ParsedIcon {
  assertWellFormedXml(source.svg, source.name);
  const document = createParser().parseFromString(source.svg, 'image/svg+xml');
  const root = document.documentElement;

  if (root.tagName !== 'svg' || root.namespaceURI !== SVG_NAMESPACE) {
    throw new Error(`Icon "${source.name}" must have a single SVG root in the SVG namespace.`);
  }

  const attributes: (readonly [string, string])[] = [];
  let viewBox: string | null = null;

  for (const name of root.getAttributeNames()) {
    const value = root.getAttribute(name) ?? '';
    if (ROOT_DISCARDED_ATTRIBUTES.has(name)) {
      continue;
    }
    if (name === 'viewBox') {
      viewBox = value;
      attributes.push(['viewBox', value]);
      continue;
    }
    if (!PRESENTATION_ATTRIBUTES.has(name)) {
      throw new Error(`Icon "${source.name}" has unsupported root attribute "${name}".`);
    }
    attributes.push([name, value]);
  }

  if (viewBox !== REQUIRED_VIEW_BOX) {
    throw new Error(`Icon "${source.name}" must declare viewBox="${REQUIRED_VIEW_BOX}", got "${viewBox ?? ''}".`);
  }

  return {name: source.name, attributes, children: parseChildren(root, source.name)};
}

function parseChildren(parent: Element, iconName: string): IconElement[] {
  const children: IconElement[] = [];

  for (const node of Array.from(parent.childNodes)) {
    const child = node as Element;
    if (child.nodeType === 3) {
      if ((child.textContent ?? '').trim() !== '') {
        throw new Error(`Icon "${iconName}" contains unexpected text content.`);
      }
      continue;
    }
    if (child.nodeType !== 1) {
      throw new Error(`Icon "${iconName}" contains an unsupported node type.`);
    }
    children.push(parseElement(child, iconName));
  }

  return children;
}

function parseElement(element: Element, iconName: string): IconElement {
  const tagName = element.tagName;
  const allowed = GEOMETRY_ATTRIBUTES[tagName];

  if (!allowed) {
    throw new Error(`Icon "${iconName}" contains unsupported element "${tagName}".`);
  }
  if (element.namespaceURI !== SVG_NAMESPACE) {
    throw new Error(`Icon "${iconName}" element "${tagName}" must live in the SVG namespace.`);
  }

  const attributes: (readonly [string, string])[] = [];
  for (const name of element.getAttributeNames()) {
    const value = element.getAttribute(name) ?? '';
    if (!allowed.has(name) && !PRESENTATION_ATTRIBUTES.has(name)) {
      throw new Error(`Icon "${iconName}" element "${tagName}" has unsupported attribute "${name}".`);
    }
    attributes.push([name, value]);
  }

  return {tagName, attributes, children: parseChildren(element, iconName)};
}

function createParser(): DOMParser {
  const window = new Window({url: 'https://localhost/'});
  return new window.DOMParser() as unknown as DOMParser;
}

function assertWellFormedXml(source: string, iconName: string): void {
  const stack: string[] = [];
  let index = 0;
  let roots = 0;

  while (index < source.length) {
    const next = source.indexOf('<', index);
    if (next === -1) {
      assertWhitespace(source.slice(index), iconName, stack);
      break;
    }
    assertWhitespace(source.slice(index, next), iconName, stack);

    if (source.startsWith('<!--', next)) {
      const end = source.indexOf('-->', next);
      if (end === -1) {
        throw malformed(iconName, 'unterminated comment');
      }
      index = end + 3;
      continue;
    }

    if (source.startsWith('<!', next) || source.startsWith('<?', next)) {
      throw malformed(iconName, 'doctype and processing instructions are not allowed');
    }

    const end = findTagEnd(source, next);
    if (end === -1) {
      throw malformed(iconName, 'unterminated tag');
    }
    const raw = source.slice(next + 1, end);
    index = end + 1;

    if (raw.startsWith('/')) {
      const open = stack.pop();
      if (open !== raw.slice(1).trim()) {
        throw malformed(iconName, `closing tag "${raw.slice(1).trim()}" does not match open tag "${open ?? ''}"`);
      }
      continue;
    }

    const selfClosing = raw.endsWith('/');
    const tagName = readTagName(raw);
    if (tagName === '') {
      throw malformed(iconName, 'missing tag name');
    }
    validateAttributes(raw.slice(tagName.length), iconName, tagName);
    if (selfClosing) {
      continue;
    }
    stack.push(tagName);
    if (stack.length === 1) {
      roots += 1;
      if (roots > 1) {
        throw malformed(iconName, 'multiple root elements');
      }
    }
  }

  if (stack.length > 0) {
    throw malformed(iconName, `unclosed tag "${stack[stack.length - 1]}"`);
  }
  if (roots === 0) {
    throw malformed(iconName, 'no root element');
  }
}

function findTagEnd(source: string, start: number): number {
  let quote: string | null = null;
  for (let index = start + 1; index < source.length; index += 1) {
    const char = source[index];
    if (quote) {
      if (char === quote) {
        quote = null;
      }
      continue;
    }
    if (char === '"' || char === '\'') {
      quote = char;
      continue;
    }
    if (char === '>') {
      return index;
    }
  }
  return -1;
}

function readTagName(raw: string): string {
  const match = /^[^\s/>]+/.exec(raw);
  return match ? match[0] : '';
}

function validateAttributes(raw: string, iconName: string, tagName: string): void {
  const body = raw.trim().replace(/\/$/, '').trim();
  const remainder = body.replace(/[^\s=]+="[^"]*"/g, '').trim();
  if (remainder !== '') {
    throw malformed(iconName, `attribute syntax is invalid in "${tagName}"`);
  }
}

function assertWhitespace(text: string, iconName: string, stack: readonly string[]): void {
  if (stack.length > 0 && text.trim() !== '') {
    throw malformed(iconName, `unexpected text content "${text.trim()}"`);
  }
}

function malformed(iconName: string, detail: string): Error {
  return new Error(`Malformed XML in icon "${iconName}": ${detail}.`);
}

function buildSprite(icons: readonly ParsedIcon[], license: string): string {
  const lines = [
    GENERATOR_HEADER,
    `<svg xmlns="${SVG_NAMESPACE}">`,
    '  <metadata>',
    escapeXmlText(license),
    '  </metadata>',
  ];

  for (const icon of icons) {
    lines.push(`  <symbol id="${SYMBOL_ID_PREFIX}${icon.name}"${serializeAttributes(icon.attributes)}>`);
    for (const child of icon.children) {
      pushElement(lines, child, 2);
    }
    lines.push('  </symbol>');
  }

  lines.push('</svg>', '');
  return lines.join('\n');
}

function pushElement(lines: string[], element: IconElement, depth: number): void {
  const indent = ' '.repeat(depth * 2);
  const attributes = serializeAttributes(element.attributes);
  if (element.children.length === 0) {
    lines.push(`${indent}<${element.tagName}${attributes} />`);
    return;
  }
  lines.push(`${indent}<${element.tagName}${attributes}>`);
  for (const child of element.children) {
    pushElement(lines, child, depth + 1);
  }
  lines.push(`${indent}</${element.tagName}>`);
}

function serializeAttributes(attributes: readonly (readonly [string, string])[]): string {
  return attributes.map(([name, value]) => ` ${name}="${escapeXmlAttribute(value)}"`).join('');
}

function escapeXmlText(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function escapeXmlAttribute(value: string): string {
  return escapeXmlText(value).replace(/"/g, '&quot;');
}

function buildNames(names: readonly string[]): string {
  const lines = [
    NAMES_HEADER,
    'export const MNDW_ICON_NAMES = [',
    ...names.map((name) => `  '${name}',`),
    '] as const;',
    '',
    'export type MndwIconName = typeof MNDW_ICON_NAMES[number];',
    '',
    'const ICON_NAMES: ReadonlySet<string> = new Set(MNDW_ICON_NAMES);',
    '',
    'export function isMndwIconName(value: string): value is MndwIconName {',
    '  return ICON_NAMES.has(value);',
    '}',
    '',
  ];
  return lines.join('\n');
}
