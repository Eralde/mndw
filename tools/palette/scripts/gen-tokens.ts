import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {type PaletteTokenMap, paletteToCss} from '@mndw/sdk/palette';
import {buildPalette} from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
// tools/palette/scripts -> repo root -> packages/sdk/src
const sdkSrc = resolve(here, '../../../packages/sdk/src');

// Font names are quoted so stylelint's value-keyword-case leaves their casing
// intact; interior comments carry a leading blank line (comment-empty-line-before).
const STATIC_TOKENS = `  /* typography */
  --mndw-font-sans: -apple-system, 'BlinkMacSystemFont', 'Segoe UI', 'Roboto', sans-serif;
  --mndw-font-mono: ui-monospace, 'SF Mono', 'Menlo', monospace;
  --mndw-text-xs: 11px;
  --mndw-text-sm: 13px;
  --mndw-text-md: 14px;
  --mndw-text-lg: 16px;
  --mndw-leading: 1.4;
  --mndw-weight-normal: 400;
  --mndw-weight-semibold: 600;

  /* spacing (4px scale) */
  --mndw-space-1: 4px;
  --mndw-space-2: 8px;
  --mndw-space-3: 12px;
  --mndw-space-4: 16px;
  --mndw-space-5: 24px;
  --mndw-space-6: 32px;

  /* radius + elevation */
  --mndw-radius-sm: 3px;
  --mndw-radius-md: 6px;
  --mndw-radius-lg: 8px;
  --mndw-shadow-1: 0 1px 3px rgb(0 0 0 / 30%);
  --mndw-shadow-2: 0 4px 16px rgb(0 0 0 / 40%);

  /* controls */
  --mndw-control-h: 32px;`;

function paletteMap(): PaletteTokenMap {
  return {light: buildPalette('light'), dark: buildPalette('dark')};
}

function renderCss(): string {
  return `/* GENERATED by tools/palette/scripts/gen-tokens.ts — do not edit by hand.
   Run: pnpm --filter @mndw/palette-tools gen-tokens */

:root {
${STATIC_TOKENS}
}

${paletteToCss(paletteMap())}`;
}

function renderTs(): string {
  const map = paletteMap();

  return `/* GENERATED by tools/palette/scripts/gen-tokens.ts — do not edit by hand. */
export const MNDW_TOKENS = ${JSON.stringify(map, null, 2)} as const;

export type MndwThemeName = keyof typeof MNDW_TOKENS;
`;
}

writeFileSync(resolve(sdkSrc, 'tokens.css'), renderCss());
writeFileSync(resolve(sdkSrc, 'tokens.ts'), renderTs());
console.log('[gen-tokens] wrote tokens.css and tokens.ts to packages/sdk/src/');
