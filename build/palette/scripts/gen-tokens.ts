import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {type PaletteTokenMap, buildPalette, paletteToCss} from '@mndw/palette-core';
import {SCALE} from '../src/scale.js';

const here = dirname(fileURLToPath(import.meta.url));
// build/palette/scripts -> repo root -> frontend/sdk/src
const sdkSrc = resolve(here, '../../../frontend/sdk/src');

// Font names are quoted so stylelint's value-keyword-case leaves their casing
// intact; interior comments carry a leading blank line (comment-empty-line-before).
function renderStaticTokens(): string {
  return `  /* typography */
  --mndw-font-sans: ${SCALE.font.sans};
  --mndw-font-mono: ${SCALE.font.mono};
  --mndw-text-xs: ${SCALE.text.xs};
  --mndw-text-sm: ${SCALE.text.sm};
  --mndw-text-md: ${SCALE.text.md};
  --mndw-text-lg: ${SCALE.text.lg};
  --mndw-leading: ${SCALE.leading};
  --mndw-weight-normal: ${SCALE.weight.normal};
  --mndw-weight-semibold: ${SCALE.weight.semibold};

  /* spacing (0.25rem scale) */
  --mndw-space-1: ${SCALE.space[1]};
  --mndw-space-2: ${SCALE.space[2]};
  --mndw-space-3: ${SCALE.space[3]};
  --mndw-space-4: ${SCALE.space[4]};
  --mndw-space-5: ${SCALE.space[5]};
  --mndw-space-6: ${SCALE.space[6]};

  /* radius + elevation */
  --mndw-radius-sm: ${SCALE.radius.sm};
  --mndw-radius-md: ${SCALE.radius.md};
  --mndw-radius-lg: ${SCALE.radius.lg};
  --mndw-shadow-1: ${SCALE.aliases.shadow1};
  --mndw-shadow-2: ${SCALE.aliases.shadow2};

  /* controls */
  --mndw-control-h: ${SCALE.control.base};
  --mndw-control-h-sm: ${SCALE.control.sm};
  --mndw-control-h-lg: ${SCALE.control.lg};
  --mndw-border-w: ${SCALE.border.width};
  --mndw-focus-w: ${SCALE.border.focusWidth};

  /* motion */
  --mndw-duration-fast: ${SCALE.motion.fast};
  --mndw-duration-base: ${SCALE.motion.base};
  --mndw-easing: ${SCALE.motion.easing};

  /* scrollbars */
  --mndw-scrollbar-size: ${SCALE.scrollbar.size};
  --mndw-scrollbar-radius: ${SCALE.scrollbar.radius};
  --mndw-scrollbar-thumb-min-size: ${SCALE.scrollbar.thumbMinSize};
  --mndw-scrollbar-track: ${SCALE.aliases.scrollbarTrack};
  --mndw-scrollbar-thumb: ${SCALE.aliases.scrollbarThumb};
  --mndw-scrollbar-thumb-hover: ${SCALE.aliases.scrollbarThumbHover};

  /* component geometry */
  --mndw-switch-w: ${SCALE.switch.width};
  --mndw-switch-h: ${SCALE.switch.height};
  --mndw-slider-track-h: ${SCALE.slider.trackHeight};
  --mndw-slider-thumb-size: ${SCALE.slider.thumbSize};
  --mndw-table-sticky-top: ${SCALE.table.stickyTop};`;
}

export function paletteMap(): PaletteTokenMap {
  return {light: buildPalette('light'), dark: buildPalette('dark')};
}

export function renderCss(): string {
  return `/* GENERATED by build/palette/scripts/gen-tokens.ts — do not edit by hand.
   Run: pnpm generate-contracts */

:root {
${renderStaticTokens()}
}

${paletteToCss(paletteMap())}`;
}

export function renderTs(): string {
  const map = paletteMap();

  return `/* GENERATED by build/palette/scripts/gen-tokens.ts — do not edit by hand. */
export const MNDW_TOKENS = ${JSON.stringify(map, null, 2)} as const;

export const MNDW_SCALE = ${JSON.stringify(SCALE, null, 2)} as const;

export type MndwThemeName = keyof typeof MNDW_TOKENS;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(resolve(sdkSrc, 'tokens.css'), renderCss());
  writeFileSync(resolve(sdkSrc, 'tokens.ts'), renderTs());
  console.log('[gen-tokens] wrote tokens.css and tokens.ts to frontend/sdk/src/');
}
