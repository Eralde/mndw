import {writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildPalette, type ThemeName, type TokenName} from '../src/index.js';

const here = dirname(fileURLToPath(import.meta.url));
// tools/palette/scripts -> repo root -> packages/sdk/src
const sdkSrc = resolve(here, '../../../packages/sdk/src');

// TokenName (camelCase) -> CSS var suffix (kebab-case).
const CSS_VAR: Record<TokenName, string> = {
  bg: 'bg',
  surface: 'surface',
  surfaceRaised: 'surface-raised',
  border: 'border',
  textSubtle: 'text-subtle',
  textMuted: 'text-muted',
  text: 'text',
  accent: 'accent',
  accentHover: 'accent-hover',
  accentContrast: 'accent-contrast',
  danger: 'danger',
  dangerBg: 'danger-bg',
  success: 'success',
  warning: 'warning',
};

// Font names are quoted so stylelint's value-keyword-case leaves their casing
// intact; interior comments carry a leading blank line (comment-empty-line-before).
const STATIC_TOKENS = `  /* typography */
  --mndw-font-sans: -apple-system, 'BlinkMacSystemFont', 'Segoe UI', 'Roboto', sans-serif;
  --mndw-font-mono: ui-monospace, 'SF Mono', 'Menlo', monospace;
  --mndw-text-xs: 11px;
  --mndw-text-sm: 13px;
  --mndw-text-md: 14px;
  --mndw-text-lg: 16px;
  --mndw-leading: 1.4;
  --mndw-weight-normal: 400;
  --mndw-weight-semibold: 600;

  /* spacing (4px scale) */
  --mndw-space-1: 4px;
  --mndw-space-2: 8px;
  --mndw-space-3: 12px;
  --mndw-space-4: 16px;
  --mndw-space-5: 24px;
  --mndw-space-6: 32px;

  /* radius + elevation */
  --mndw-radius-sm: 3px;
  --mndw-radius-md: 6px;
  --mndw-radius-lg: 8px;
  --mndw-shadow-1: 0 1px 3px rgb(0 0 0 / 30%);
  --mndw-shadow-2: 0 4px 16px rgb(0 0 0 / 40%);

  /* controls */
  --mndw-control-h: 32px;`;

function colorBlock(theme: ThemeName): string {
  const palette = buildPalette(theme);

  return (Object.keys(CSS_VAR) as TokenName[])
    .map((token) => `  --mndw-${CSS_VAR[token]}: ${palette[token]};`)
    .join('\n');
}

function renderCss(): string {
  return `/* GENERATED by tools/palette/scripts/gen-tokens.ts — do not edit by hand.
   Run: pnpm --filter @mndw/palette-tools gen-tokens */

:root {
${STATIC_TOKENS}
}

:root,
:root[data-theme='dark'] {
${colorBlock('dark')}
}

:root[data-theme='light'] {
${colorBlock('light')}
}
`;
}

function renderTs(): string {
  const map: Record<ThemeName, Record<TokenName, string>> = {
    light: buildPalette('light'),
    dark: buildPalette('dark'),
  };

  return `/* GENERATED by tools/palette/scripts/gen-tokens.ts — do not edit by hand. */
export const MNDW_TOKENS = ${JSON.stringify(map, null, 2)} as const;

export type MndwThemeName = keyof typeof MNDW_TOKENS;
`;
}

writeFileSync(resolve(sdkSrc, 'tokens.css'), renderCss());
writeFileSync(resolve(sdkSrc, 'tokens.ts'), renderTs());
console.log('[gen-tokens] wrote tokens.css and tokens.ts to packages/sdk/src/');
